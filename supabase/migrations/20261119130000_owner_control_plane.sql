-- Owner control plane. Review and apply only in an isolated Supabase environment first.
-- No payment provider or existing tenant data is changed by this migration.

CREATE TABLE IF NOT EXISTS public.tenant_entitlements (
  tenant_id uuid PRIMARY KEY REFERENCES public.tenants(id) ON DELETE CASCADE,
  plan text NOT NULL DEFAULT 'starter' CHECK (plan IN ('starter', 'pro')),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.owner_members (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email text NOT NULL UNIQUE,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.tenant_controls (
  tenant_id uuid PRIMARY KEY REFERENCES public.tenants(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'active', 'suspended', 'blocked', 'archived')),
  plan text NOT NULL DEFAULT 'starter' CHECK (plan IN ('starter', 'pro')),
  plan_expires_at timestamptz,
  approved_at timestamptz,
  updated_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.owner_audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  action text NOT NULL,
  tenant_id uuid REFERENCES public.tenants(id) ON DELETE SET NULL,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.owner_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tenant_controls ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.owner_audit_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.owner_members, public.tenant_controls, public.owner_audit_log FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.owner_members, public.tenant_controls, public.owner_audit_log TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.owner_audit_log_id_seq TO service_role;

CREATE INDEX IF NOT EXISTS owner_audit_log_tenant_created_idx ON public.owner_audit_log (tenant_id, created_at DESC);
CREATE INDEX IF NOT EXISTS tenant_controls_status_idx ON public.tenant_controls (status);

CREATE OR REPLACE FUNCTION public.get_public_tenant_control(p_slug text)
RETURNS TABLE(status text, plan text, plan_expires_at timestamptz)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
  SELECT COALESCE(c.status, 'active'), COALESCE(c.plan, 'starter'), c.plan_expires_at
  FROM public.tenants AS t
  LEFT JOIN public.tenant_controls AS c ON c.tenant_id = t.id
  WHERE t.slug = lower(trim(p_slug))
  LIMIT 1
$$;
REVOKE ALL ON FUNCTION public.get_public_tenant_control(text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.get_public_tenant_control(text) TO anon, authenticated;
